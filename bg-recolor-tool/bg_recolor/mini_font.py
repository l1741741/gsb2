GLYPH_W = 5
GLYPH_H = 7


def text_width(text: str, scale: int = 1) -> int:
    return len(text) * (GLYPH_W + 1) * scale - scale


def draw_text(img, text: str, x: int, y: int, rgb, scale: int = 2) -> None:
    """在 ImageData 上绘制位图文字；未知字符按空格处理。"""
    from .artifacts import _set_opaque  # 局部导入避免循环

    cx = x
    for ch in text.upper():
        glyph = GLYPHS.get(ch, GLYPHS[" "])
        for row, line in enumerate(glyph):
            for col, mark in enumerate(line):
                if mark != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        _set_opaque(img, cx + col * scale + sx,
                                    y + row * scale + sy, rgb)
        cx += (GLYPH_W + 1) * scale
